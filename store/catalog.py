def laptop_specs(cpu, ram, storage, display, gpu, weight, os="Windows 11 Home", battery=None):
    short_cpu = cpu.replace("Intel ", "").replace("AMD ", "").replace("Apple ", "")
    specs = {
        "summary": f"{short_cpu} · {ram} · {storage}",
        "Processor": cpu, "Memory": ram, "Storage": storage, "Display": display,
        "Graphics": gpu, "Operating system": os, "Weight": weight,
    }
    if battery:
        specs["Battery"] = battery
    return specs


# Machine-readable fields for the PC builder; stored under specs["compat"].
COMPAT_KEYS = {"socket", "memory_type", "form_factor", "form_factors", "tdp", "wattage", "integrated_graphics"}


def P(cat, name, brand, price, stock, desc, specs=None, art=None, featured=False):
    specs = dict(specs or {})
    compat = {k: specs.pop(k) for k in list(specs) if k in COMPAT_KEYS}
    if compat:
        specs["compat"] = compat
    return dict(cat=cat, name=name, brand=brand, price=price, stock=stock, desc=desc,
                specs=specs, art=art, featured=featured)


